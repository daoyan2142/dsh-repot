/**
 * The configuration set: the files that describe *how this profile is wired*,
 * and nothing that can be regenerated or is machine-specific.
 *
 * `cordis.yml` is a generated `[]` root and is deliberately excluded — copying
 * it would overwrite whatever the target machine composes from its bundles.
 *
 * `pnpm-lock.yaml` is excluded too. It is not a description of the profile: it
 * is a resolution record stamped with this machine's absolute paths, so a fresh
 * `pnpm install` on the target regenerates it correctly while a copied one
 * pins the target to paths that do not exist there.
 */
import { stat } from 'node:fs/promises'
import { join } from 'node:path'

/** Carried verbatim. */
export const CONFIG_FILES = ['cordis.patch.yml', 'package.json', 'pnpm-workspace.yaml']

/** Present in the profile but never carried: regenerated by the package manager. */
export const LOCKFILE = 'pnpm-lock.yaml'

/** Present in the profile but never carried. */
export const GENERATED_FILES = ['cordis.yml']

export async function scanConfig(profileDir) {
  const items = []
  const skipped = []

  for (const relPath of CONFIG_FILES) {
    const absPath = join(profileDir, relPath)
    try {
      const info = await stat(absPath)
      items.push({ relPath, absPath, bytes: info.size, mtimeMs: Math.round(info.mtimeMs) })
    } catch {
      skipped.push({ relPath, reason: 'missing' })
    }
  }

  skipped.push({ relPath: LOCKFILE, reason: 'machine-specific' })
  for (const relPath of GENERATED_FILES) skipped.push({ relPath, reason: 'generated' })

  return {
    items,
    skipped,
    bytes: items.reduce((sum, item) => sum + item.bytes, 0),
  }
}
